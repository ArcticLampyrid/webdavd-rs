//! cloud-init seed of one case: `meta-data`, and `#cloud-config` `user-data`
//! for cloud-init (Linux) and nuageinit (FreeBSD).
//!
//! `write_files` writes the files of the profile, the step scripts and the
//! runner. Both tools write these files before the network starts. `runcmd`
//! starts the runner late in the boot, when the network is available. The
//! runner runs the profile steps, then the case steps with the case
//! environment. Then it prints `E2E_HARNESS_EXIT:<status>` on the console and
//! powers off the guest. `images/entrypoint.sh` reads that line.

use anyhow::Result;
use base64::prelude::{Engine, BASE64_STANDARD};
use serde::Serialize;

use crate::config::{Case, Step};

/// Directory for the runner and the step scripts. nuageinit does not create
/// parent directories, so it must exist in all guests.
const GUEST_DIR: &str = "/var/tmp";

/// Fixed part of the runner script. Steps and environment come after it.
const RUNNER_HEADER: &str = r#"#!/bin/sh
# Runner of one E2E case, generated by e2e-harness.
# It runs the steps in sequence and stops at the first failure. Then it
# prints the result on the console, and powers off the guest.

# The console is the serial port that the container records. Unlike
# /dev/ttyS0 on Linux, /dev/console stays open when a getty hangs up the port.
exec </dev/null >/dev/console 2>&1
export HOME=/root
export PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin
cd /root || exit

# run_step LABEL SHELL SCRIPT
run_step() {
    echo "e2e: step $1: start"
    "$2" "$3"
    status=$?
    echo "e2e: step $1: exit status $status"
    return "$status"
}

# finish STATUS
finish() {
    printf '%s:%s\n' E2E_HARNESS_EXIT "$1"
    sync
    poweroff
    exit "$1"
}

"#;

/// The two files of the `cidata` volume.
#[derive(Debug)]
pub struct Seed {
    pub meta_data: String,
    pub user_data: String,
}

#[derive(Serialize)]
struct MetaData {
    #[serde(rename = "instance-id")]
    instance_id:    String,
    #[serde(rename = "local-hostname")]
    local_hostname: &'static str,
}

#[derive(Serialize)]
struct CloudConfig {
    write_files: Vec<CloudFile>,
    runcmd:      Vec<String>,
}

/// A `write_files` entry. The content is base64, so that no YAML parser can change it.
#[derive(Serialize)]
struct CloudFile {
    path:        String,
    encoding:    &'static str,
    content:     String,
    #[serde(skip_serializing_if = "Option::is_none")]
    permissions: Option<String>,
}

/// A step script in the guest.
struct GuestStep {
    label: String,
    shell: String,
    path:  String,
    run:   String,
}

impl CloudFile {
    fn new(path: &str, content: &str, permissions: Option<&str>) -> Self {
        CloudFile {
            path:        path.to_owned(),
            encoding:    "b64",
            content:     BASE64_STANDARD.encode(content),
            permissions: permissions.map(str::to_owned),
        }
    }
}

/// The seed for `case`. `env` goes to the case steps only, not to the profile steps.
pub fn seed(case: &Case, env: &[(String, String)]) -> Result<Seed> {
    let profile = &case.profile;
    let profile_steps = guest_steps(&format!("vm-profile {}", profile.name), &profile.steps, 0);
    let case_steps = guest_steps(&format!("case {}", case.name), &case.steps, profile_steps.len());
    let runner_path = format!("{GUEST_DIR}/e2e-runner");
    let runner = runner_script(&profile_steps, &case_steps, env);

    let write_files = profile
        .write_files
        .iter()
        .map(|file| CloudFile::new(&file.path, &file.content, file.permissions.as_deref()))
        .chain(
            profile_steps
                .iter()
                .chain(&case_steps)
                .map(|step| CloudFile::new(&step.path, &step.run, Some("0700"))),
        )
        .chain([CloudFile::new(&runner_path, &runner, Some("0700"))])
        .collect();
    let user_data = CloudConfig {
        write_files,
        runcmd: vec![format!("sh {runner_path}")],
    };
    let meta_data = MetaData {
        instance_id:    format!("webdavd-e2e-{}", case.name),
        local_hostname: "webdavd-e2e",
    };
    Ok(Seed {
        meta_data: to_yaml(&meta_data)?,
        user_data: format!("#cloud-config\n{}", to_yaml(&user_data)?),
    })
}

/// YAML with plain or quoted scalars only: no block scalars for the long base64 lines.
fn to_yaml(value: &impl Serialize) -> Result<String> {
    let options = serde_saphyr::ser_options! { prefer_block_scalars: false };
    Ok(serde_saphyr::to_string_with_options(value, options)?)
}

/// Steps with labels such as `case foo: 2 (start webdavd)`, and script files numbered from `first + 1`.
fn guest_steps(owner: &str, steps: &[Step], first: usize) -> Vec<GuestStep> {
    steps
        .iter()
        .map(Step::script)
        .enumerate()
        .map(|(index, step)| {
            let number = index + 1;
            let label = match &step.name {
                Some(name) => format!("{owner}: {number} ({name})"),
                None => format!("{owner}: {number}"),
            };
            GuestStep {
                label,
                shell: step.shell.clone(),
                path: format!("{GUEST_DIR}/e2e-step-{}", first + number),
                run: step.run.clone(),
            }
        })
        .collect()
}

fn runner_script(profile_steps: &[GuestStep], case_steps: &[GuestStep], env: &[(String, String)]) -> String {
    let run = |step: &GuestStep| {
        format!(
            "run_step {} {} {} || finish $?\n",
            shell_quote(&step.label),
            shell_quote(&step.shell),
            shell_quote(&step.path)
        )
    };
    let export = |(key, value): &(String, String)| format!("export {key}={}\n", shell_quote(value));

    let mut script = RUNNER_HEADER.to_owned();
    script.extend(profile_steps.iter().map(run));
    script.extend(env.iter().map(export));
    script.extend(case_steps.iter().map(run));
    script.push_str("finish 0\n");
    script
}

/// `text` as one word for a POSIX shell.
fn shell_quote(text: &str) -> String {
    format!("'{}'", text.replace('\'', r"'\''"))
}

#[cfg(test)]
mod tests {
    use std::process::Command;

    use super::*;
    use crate::config::fixtures::case;

    fn env() -> Vec<(String, String)> {
        vec![
            (
                "ASSETS_BASE_URL".to_owned(),
                "http://10.0.2.100:8000/cases/demo/assets".to_owned(),
            ),
            ("WEBDAVD_BIN".to_owned(), "target/it's here/webdavd".to_owned()),
        ]
    }

    #[derive(serde::Deserialize)]
    struct ParsedFile {
        path:        String,
        encoding:    String,
        content:     String,
        permissions: Option<String>,
    }

    #[derive(serde::Deserialize)]
    struct ParsedConfig {
        write_files: Vec<ParsedFile>,
        runcmd:      Vec<String>,
    }

    fn parse_user_data(user_data: &str) -> ParsedConfig {
        let body = user_data
            .strip_prefix("#cloud-config\n")
            .expect("user-data starts with #cloud-config");
        serde_saphyr::from_str(body).unwrap()
    }

    fn decode(file: &ParsedFile) -> String {
        assert_eq!(file.encoding, "b64");
        String::from_utf8(BASE64_STANDARD.decode(&file.content).unwrap()).unwrap()
    }

    #[test]
    fn seed_files_and_runcmd() {
        let seed = seed(&case(), &env()).unwrap();
        assert!(seed.meta_data.contains("instance-id: webdavd-e2e-demo"));
        // Quoted: an unquoted 0644 is a number in YAML 1.1 (cloud-init, nuageinit).
        assert!(
            seed.user_data.contains("permissions: \"0644\"\n"),
            "{}",
            seed.user_data
        );
        assert!(!seed.user_data.contains(": >"), "{}", seed.user_data);

        let config = parse_user_data(&seed.user_data);
        let paths: Vec<_> = config.write_files.iter().map(|file| file.path.as_str()).collect();
        assert_eq!(
            paths,
            [
                "/etc/rc.conf.d/example",
                "/var/tmp/e2e-step-1",
                "/var/tmp/e2e-step-2",
                "/var/tmp/e2e-step-3",
                "/var/tmp/e2e-runner",
            ]
        );
        assert_eq!(decode(&config.write_files[0]), "example_enable=\"NO\"\n");
        assert_eq!(config.write_files[0].permissions.as_deref(), Some("0644"));
        assert_eq!(decode(&config.write_files[2]), "echo \"$WEBDAVD_BIN\"\n");
        assert_eq!(config.write_files[4].permissions.as_deref(), Some("0700"));
        assert_eq!(config.runcmd, ["sh /var/tmp/e2e-runner"]);
    }

    #[test]
    fn runner_exports_env_only_for_case_steps() {
        let seed = seed(&case(), &env()).unwrap();
        let config = parse_user_data(&seed.user_data);
        let runner = decode(config.write_files.last().unwrap());
        let body = runner.strip_prefix(RUNNER_HEADER).unwrap();
        assert_eq!(
            body,
            "run_step 'vm-profile os-1: 1 (prepare)' 'sh' '/var/tmp/e2e-step-1' || finish $?\n\
             export ASSETS_BASE_URL='http://10.0.2.100:8000/cases/demo/assets'\n\
             export WEBDAVD_BIN='target/it'\\''s here/webdavd'\n\
             run_step 'case demo: 1' 'bash' '/var/tmp/e2e-step-2' || finish $?\n\
             run_step 'case demo: 2 (it'\\''s ok)' 'sh' '/var/tmp/e2e-step-3' || finish $?\n\
             finish 0\n"
        );
    }

    /// The quoted words survive `sh` unchanged.
    #[test]
    fn shell_quote_round_trip() {
        for text in [
            "",
            "plain",
            "it's",
            "a b",
            "$HOME `id` \"q\" \\ \n new line",
            "'''",
        ] {
            let output = Command::new("sh")
                .arg("-c")
                .arg(format!("printf %s {}", shell_quote(text)))
                .output()
                .unwrap();
            assert_eq!(String::from_utf8(output.stdout).unwrap(), text);
        }
    }

    /// The runner stops at the first failed step and reports its status.
    #[test]
    fn runner_stops_at_first_failure() {
        let dir = tempfile::tempdir().unwrap();
        let step = |n: u8, run: &str| {
            let path = dir.path().join(format!("step-{n}"));
            std::fs::write(&path, run).unwrap();
            GuestStep {
                label: format!("step {n}"),
                shell: "sh".to_owned(),
                path:  path.to_str().unwrap().to_owned(),
                run:   run.to_owned(),
            }
        };
        let profile_steps = [step(1, "test -z \"$CASE_VALUE\"\n")];
        let case_steps = [
            step(2, "test \"$CASE_VALUE\" = \"it's\"\n"),
            step(3, "exit 7\n"),
            step(4, "echo unreachable\n"),
        ];
        let env = [("CASE_VALUE".to_owned(), "it's".to_owned())];
        // Run the generated steps without the console redirect and the power-off.
        let runner = runner_script(&profile_steps, &case_steps, &env)
            .replace("exec </dev/null >/dev/console 2>&1\n", "")
            .replace("cd /root || exit\n", "")
            .replace("    poweroff\n", "");
        let output = Command::new("sh").arg("-c").arg(runner).output().unwrap();
        let stdout = String::from_utf8(output.stdout).unwrap();
        assert_eq!(output.status.code(), Some(7), "{stdout}");
        assert!(stdout.contains("e2e: step step 2: exit status 0\n"), "{stdout}");
        assert!(
            stdout.ends_with("e2e: step step 3: exit status 7\nE2E_HARNESS_EXIT:7\n"),
            "{stdout}"
        );
        assert!(!stdout.contains("unreachable"));
    }
}
